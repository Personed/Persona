import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import type { z } from "zod";
import { procedures, routerProcedures } from "./procedures.ts";

// Records how the router's Zod schemas answer generated inputs, so the Go validator in
// internal/rpc can be checked against Zod without running Node.
const contract = new URL("../../../contracts/api/", import.meta.url);
const target = fileURLToPath(
  new URL("../../../internal/rpc/testdata/zod-issues.json", import.meta.url),
);

const samples: unknown[] = [
  123,
  -1,
  1.5,
  "",
  "  x  ",
  "x".repeat(600),
  "not a url",
  "https://example.com",
  "ftp://example.com",
  "00000000-0000-0000-0000-000000000000",
  "a\u0000b",
  true,
  null,
  [],
  ["x"],
  {},
  { unknown: 1 },
];

const bases = new Map<string, Record<string, unknown>[]>();
for (const file of await readdir(new URL("fixtures/", contract))) {
  const exchanges = JSON.parse(
    await readFile(new URL(`fixtures/${file}`, contract), "utf8"),
  ) as Array<{ procedure: string; request: { body: { json?: unknown } } }>;
  for (const { procedure, request } of exchanges)
    if (request.body.json !== undefined)
      bases.set(procedure, [
        ...(bases.get(procedure) ?? []),
        JSON.parse(
          JSON.stringify(request.body.json).replaceAll(
            "<uuid>",
            "00000000-0000-0000-0000-000000000000",
          ),
        ),
      ]);
}

function inputs(path: string, schema: Record<string, unknown>) {
  const list: unknown[] = [undefined, ...samples];
  const properties = Object.keys(
    (schema.properties as Record<string, unknown>) ?? {},
  );
  for (const base of [{}, ...(bases.get(path) ?? [])]) {
    list.push(base, { ...base, extra: 1 });
    for (const key of properties)
      for (const value of samples) list.push({ ...base, [key]: value });
  }
  return list;
}

const schemas = routerProcedures();
const seen = new Set<string>();
const cases = procedures().flatMap(({ path, input }) => {
  const schema = schemas.get(path) as z.ZodType | undefined;
  if (!schema || !input) return [];
  return inputs(path, input as Record<string, unknown>).flatMap((value) => {
    const result = schema.safeParse(value);
    const answer = result.success
      ? { output: result.data ?? null }
      : { issues: result.error.issues };
    // Keep one input per distinct answer.
    const key = JSON.stringify([path, answer]);
    if (seen.has(key)) return [];
    seen.add(key);
    return [JSON.stringify({ path, input: value, ...answer })];
  });
});
const text = `{"$comment":"Generated by \`node apps/api/contract/zod-issues.ts\` from apps/api/src/router.ts. Do not edit.","cases":[\n${cases.join(",\n")}\n]}\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== text) {
    console.error(
      "internal/rpc/testdata/zod-issues.json is stale. Run `node apps/api/contract/zod-issues.ts`.",
    );
    process.exitCode = 1;
  }
} else await writeFile(target, text);
